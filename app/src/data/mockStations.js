export function simulateStationFluctuation(station) {
  const now = new Date().toISOString()
  const levelDelta = (Math.random() - 0.49) * 0.02
  const newLevel = station.level != null ? Number(Math.max(0.1, station.level + levelDelta).toFixed(2)) : null

  const tempDelta = (Math.random() - 0.5) * 0.15
  const newTemp = station.temperature?.current != null
    ? Number((station.temperature.current + tempDelta).toFixed(1))
    : null

  const windDelta = (Math.random() - 0.5) * 0.4
  const newWind = station.wind?.speed != null
    ? Number(Math.max(0, station.wind.speed + windDelta).toFixed(1))
    : null

  const pressureDelta = (Math.random() - 0.5) * 0.2
  const newPressure = station.pressure?.current != null
    ? Number((station.pressure.current + pressureDelta).toFixed(1))
    : null

  return {
    ...station,
    measuredAt: now,
    _lastUpdated: Date.now(),
    level: newLevel,
    currentLevel: newLevel ?? station.currentLevel,
    temperature: station.temperature ? {
      ...station.temperature,
      current: newTemp,
    } : station.temperature,
    wind: station.wind ? {
      ...station.wind,
      speed: newWind,
    } : station.wind,
    pressure: station.pressure ? {
      ...station.pressure,
      current: newPressure,
    } : station.pressure,
  }
}
